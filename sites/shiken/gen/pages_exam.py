def n(x) -> str:
    return f"{x:,}"


def drow(label: str, iso: str) -> list:
    return [label, jp(iso), in_days(iso)]


def dates_table(caption: str, rows: list[list], note: str = "") -> dict:
    t = {"caption": caption, "cols": ["区分", "日付", f"{today_j()}から"], "rows": rows}
    if note:
        t["note"] = note
    return t


def rate_table(caption: str, rows: list[dict], first: str = "年度", note: str = "") -> dict:
    out = []
    for r in rows:
        rate = r.get("rate") if r.get("rate") is not None else r.get("rate_computed")
        app = r.get("applicants")
        out.append([r["year"], n(app) if app else "—", n(r["examinees"]), n(r["passed"]), f"{rate:.1f}%" if rate is not None else "—"])
    t = {"caption": caption, "cols": [first, "申込者", "受験者", "合格者", "合格率"], "num_cols": [1, 2, 3, 4], "rows": out}
    if note:
        t["note"] = note
    return t


def official(*pairs) -> str:
    return '<ul class="links">' + "".join(f'<li><a href="{u}" rel="noopener" target="_blank">{t}</a></li>' for t, u in pairs) + "</ul>"


def item(path, kw, title, h1, desc, answer, secs, related, sources, basis, intent=1, secondary=()):
    return {"path": path, "kind": "item", "parent": "/schedule/", "primary_kw": kw, "secondary_kw": list(secondary), "intent": intent,
            "title": title, "h1": h1, "description": desc, "answer": answer, "data_basis": basis, "sections": secs, "related": related, "sources": sources}


