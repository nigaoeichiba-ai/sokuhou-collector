def by_slug(slug: str) -> dict | None:
    for u in USECASES:
        if u["slug"] == slug:
            return u
    return None


def related(slug: str) -> list[dict]:
    """The scenarios a scenario points to (existing ones only, in the written order)."""
    u = by_slug(slug)
    if not u:
        return []
    return [r for r in (by_slug(s) for s in u["related"]) if r]


def grouped() -> list[tuple[str, list[dict]]]:
    """Scenarios by group in the display order (groups with no scenario are left out)."""
    out = []
    for g in GROUPS_ORDER:
        items = [u for u in USECASES if u["group"] == g]
        if items:
            out.append((g, items))
    return out
