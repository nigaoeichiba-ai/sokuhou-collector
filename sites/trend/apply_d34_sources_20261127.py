FIELDS = ("sections", "description", "answer", "top_lead", "todo", "secondary_kw")


def edit(slug):
    path = os.path.join(CONTENT, "trend-%s.json" % slug)
    d = json.load(open(path, encoding="utf-8"))
    before = json.dumps(d, ensure_ascii=False)
    pairs = BODY.get(slug, []) + COMMON
    used = set()

    def walk(v):
        if isinstance(v, str):
            for old, new in pairs:
                if old in v and new not in v:
                    used.add(old)
                    v = v.replace(old, new)
            return v
        if isinstance(v, list):
            return [walk(x) for x in v]
        if isinstance(v, dict):
            return {k: walk(x) for k, x in v.items()}
        return v

    for k in FIELDS:
        if k in d:
            d[k] = walk(d[k])
    d["credit"] = CREDIT[slug]
    if json.dumps(d, ensure_ascii=False) == before:
        return None
    open(path, "w", encoding="utf-8", newline="").write(json.dumps(d, ensure_ascii=False, indent=1) + "\n")
    return [old for old, _ in BODY.get(slug, []) if old not in used]


