def pointdays(n=8):
    out, x = [], TODAY
    while len(out) < n:
        if x.day in (5, 10, 15, 20, 25, 30):
            out.append(x)
        x += timedelta(days=1)
    return out


def next_sentence(g: str, name: str, unannounced: str) -> str:
    up = upcoming(g)
    if up:
        e = up[0]
        if phase(e) == "now":
            return f"{name}は開催中で、{ev_span(e)}です。"
        return f"次の{name}は{ev_span(e)}です。{until(e['start'])}に始まります。"
    return unannounced


