def open_days(start: date, end: date, holidays: set[date], closed: tuple[date, date] | None = None) -> int:
    """weekdays from start to end (both included) that are neither a holiday nor inside the closed period of the national offices"""
    n, x = 0, start
    while x <= end:
        if x.weekday() < 5 and x not in holidays and not (closed and closed[0] <= x <= closed[1]):
            n += 1
        x = plus(x, 1)
    return n


