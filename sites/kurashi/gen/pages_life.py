def add_months(x, n):
    """The day that corresponds to x, n months later (Civil Code art. 143: the period ends on the day before the corresponding day; the callers pass the start already shifted)."""
    y, m = divmod(x.month - 1 + n, 12)
    return x.replace(year=x.year + y, month=m + 1)


